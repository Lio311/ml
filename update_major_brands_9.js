  for (const brand of brandsData) {
    await pool.query(
      'UPDATE brands SET title = $1, description = $2, highlights = $3, perfumer = $4 WHERE name ILIKE $5',
      [brand.title, brand.description, brand.highlights, brand.perfumer, `%${brand.name}%`]
    );
    console.log(`Updated ${brand.name}`);
  }
