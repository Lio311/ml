export const getBrandInsight = (brandName) => {
    if (!brandName) return null;
    
    // Normalize brand name for matching
    const normalized = brandName.trim();
    
    // Exact match direct
    if (brandData[normalized]) return brandData[normalized];
    
    // Try Case-insensitive match or contains
    const foundKey = Object.keys(brandData).find(key => 
        key.toLowerCase() === normalized.toLowerCase() || 
        normalized.toLowerCase().includes(key.toLowerCase())
    );
    
    if (foundKey) return brandData[foundKey];
    
    // Generic fallback for SEO
    return {
        title: `עולם הבישום של ${normalized}`,
        description: `${normalized} הוא בית בישום המוקדש ליצירת ניחוחות איכותיים ומיוחדים. המותג מתמקד בשימוש בחומרי גלם מעולים כדי להעניק חווית ריח ייחודית, עמידה ומרגשת. כל יצירה של המותג נבחרה בקפידה ב-ml_tlv כדי להבטיח איכות ללא פשרות.`,
        perfumer: 'אמני בישום בינלאומיים',
        highlights: 'איכות ללא פשרות, חומרי גלם מעולים, וניחוחות בעלי חתימה אישית.'
    };
};
